// Every text file the tool writes goes through tpmx::format, which must print the same bytes on
// every C runtime: "%f" exact with ties rounded to even (glibc, and the Windows UCRT since
// Windows 10 2004), NaN spelled as the UCRT does. Checked here:
//   - a fixed table of formats and values (expected strings from an exact C library);
//   - the NaN and infinity spellings;
//   - with glibc only: a seeded differential against snprintf over random float bit patterns,
//     dyadic values with many exact ties, random doubles and integers.
// Exit 0 = pass, 1 = fail.

#include "textout.h"

#include <cinttypes>
